function evaluation = evaluate_core(data, theta, known)

allTruth = [];
allPrediction = [];
perLoad = table();

for l = 1:data.n_loads
    seg = data.segments{l};
    transitionIdx = seg.test_transition_idx;
    prediction = zeros(numel(transitionIdx)+1, 2);
    prediction(1,:) = seg.y(seg.test_state_idx(1),:);
    for j = 1:numel(transitionIdx)
        k = transitionIdx(j);
        prediction(j+1,:) = nate.step(prediction(j,:), seg.switch_state(k), ...
            seg.dt(k), seg.Rload, theta, known);
    end
    truth = seg.y(seg.test_state_idx,:);
    error = prediction(2:end,:) - truth(2:end,:);

    loadTable = table(l, seg.Rload, ...
        sqrt(mean(error(:,1).^2)), sqrt(mean(error(:,2).^2)), ...
        mean(abs(error(:,1))), mean(abs(error(:,2))), ...
        max(abs(error(:,1))), max(abs(error(:,2))), ...
        abs(error(end,1)), abs(error(end,2)), ...
        'VariableNames', {'load_index','Rload_ohm','current_rmse_A','voltage_rmse_V', ...
        'current_mae_A','voltage_mae_V','current_max_abs_A','voltage_max_abs_V', ...
        'current_terminal_abs_A','voltage_terminal_abs_V'});
    perLoad = [perLoad; loadTable];
    allTruth = [allTruth; truth(2:end,:)];
    allPrediction = [allPrediction; prediction(2:end,:)];
end

error = allPrediction - allTruth;
evaluation.summary = struct( ...
    'current_rmse_A',sqrt(mean(error(:,1).^2)), ...
    'voltage_rmse_V',sqrt(mean(error(:,2).^2)), ...
    'current_mae_A',mean(abs(error(:,1))), ...
    'voltage_mae_V',mean(abs(error(:,2))), ...
    'current_max_abs_A',max(abs(error(:,1))), ...
    'voltage_max_abs_V',max(abs(error(:,2))));
evaluation.per_load = perLoad;
evaluation.truth = allTruth;
evaluation.prediction = allPrediction;
end
